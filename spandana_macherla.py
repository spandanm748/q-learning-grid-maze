def evaluate_agent(
    q_table,
    evaluation_episodes=100
):

    evaluation_rewards = []
    evaluation_steps = []
    evaluation_success = []

    for episode in range(evaluation_episodes):

        state = reset_environment()

        total_reward = 0
        steps = 0
        success = False

        for step in range(MAX_STEPS):

            steps += 1

            # No exploration during evaluation
            action = get_greedy_action(
                q_table,
                state
            )

            next_state, reward, done = take_action(
                state,
                action
            )

            total_reward += reward

            state = next_state

            if done:
                success = True
                break

        evaluation_rewards.append(
            total_reward
        )

        evaluation_steps.append(
            steps
        )

        evaluation_success.append(
            1 if success else 0
        )

    return (
        evaluation_rewards,
        evaluation_steps,
        evaluation_success
    )


