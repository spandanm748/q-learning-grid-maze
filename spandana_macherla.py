def get_greedy_action(q_table, state):

    state_index = state_to_index(state)

    q_values = q_table[state_index]

    return int(np.argmax(q_values))


def get_greedy_path(q_table):

    state = START

    path = [state]

    actions_taken = []

    visited = set()

    for step in range(MAX_STEPS):

        if state == GOAL:
            break

        # Prevent infinite loops
        if state in visited:
            break

        visited.add(state)

        action = get_greedy_action(
            q_table,
            state
        )

        next_state, reward, done = take_action(
            state,
            action
        )

        actions_taken.append(
            ACTION_NAMES[action]
        )

        path.append(next_state)

        state = next_state

        if done:
            break

    return path, actions_taken


