RIGHT = 3

ACTIONS = [UP, DOWN, LEFT, RIGHT]

ACTION_NAMES = {
    UP: "Up",
    DOWN: "Down",
    LEFT: "Left",
    RIGHT: "Right"
}

# ============================================================
# 2. MAZE DEFINITION
