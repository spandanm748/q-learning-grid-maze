OBSTACLES = {
    (0, 3),
    (1, 0),
    (1, 2),
    (2, 4),
    (3, 1),
    (3, 2)
}

# ============================================================
# 3. ENVIRONMENT FUNCTIONS
# ============================================================

def state_to_index(state):
    """
    Convert row and column into a single state index.
    """
    row, col = state
    return row * GRID_SIZE + col


def index_to_state(index):
    """
    Convert state index back to row and column.
    """
    row = index // GRID_SIZE
    col = index % GRID_SIZE
    return (row, col)


def reset_environment():
    """
    Reset the environment to the starting position.
    """
    return START


def take_action(state, action):
    """
    Execute an action and return:
    next_state, reward, done
    """

    row, col = state

    if action == UP:
        new_row = row - 1
        new_col = col

    elif action == DOWN:
        new_row = row + 1
        new_col = col

    elif action == LEFT:
        new_row = row
        new_col = col - 1

    elif action == RIGHT:
        new_row = row
        new_col = col + 1

    else:
        return state, INVALID_REWARD, False

    # Check grid boundaries
    if (
        new_row < 0
        or new_row >= GRID_SIZE
        or new_col < 0
        or new_col >= GRID_SIZE
    ):
        return state, INVALID_REWARD, False

    next_state = (new_row, new_col)

    # Check obstacle
    if next_state in OBSTACLES:
        return state, OBSTACLE_REWARD, False

    # Check goal
    if next_state == GOAL:
        return next_state, GOAL_REWARD, True

    # Normal movement
    return next_state, MOVE_REWARD, False


# ============================================================
# 4. EPSILON-GREEDY ACTION SELECTION
# ============================================================

def choose_action(q_table, state, epsilon):
    """
    Select an action using epsilon-greedy exploration.
    """

    state_index = state_to_index(state)

    # Exploration
    if np.random.random() < epsilon:
        return np.random.choice(ACTIONS)

    # Exploitation
    q_values = q_table[state_index]

    max_q = np.max(q_values)

    # Handle ties randomly
    best_actions = np.where(q_values == max_q)[0]

    return np.random.choice(best_actions)


