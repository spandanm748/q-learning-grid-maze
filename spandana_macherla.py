# 5. TRAINING FUNCTION
# ============================================================

def train_q_learning(seed=123):
    """
    Train a Q-learning agent.
    """

    np.random.seed(seed)

    # 25 states x 4 actions
    q_table = np.zeros((GRID_SIZE * GRID_SIZE, 4))

    episode_rewards = []
    episode_steps = []
    episode_success = []
    epsilon_values = []

    epsilon = INITIAL_EPSILON

    for episode in range(TRAINING_EPISODES):

        state = reset_environment()

        total_reward = 0
        steps = 0
        success = False

        for step in range(MAX_STEPS):

            steps += 1

            # Select action
            action = choose_action(
                q_table,
                state,
                epsilon
            )

            # Take action
            next_state, reward, done = take_action(
                state,
                action
            )

            current_index = state_to_index(state)
            next_index = state_to_index(next_state)

            # Current Q-value
            current_q = q_table[current_index, action]

            # Maximum future Q-value
            if done:
                max_future_q = 0
            else:
                max_future_q = np.max(q_table[next_index])

            # Q-learning update
            new_q = current_q + LEARNING_RATE * (
                reward
                + DISCOUNT_FACTOR * max_future_q
                - current_q
            )

            q_table[current_index, action] = new_q

            # Update state
            state = next_state

            total_reward += reward

            if done:
                success = True
                break

        # Store results
        episode_rewards.append(total_reward)
        episode_steps.append(steps)
        episode_success.append(1 if success else 0)
        epsilon_values.append(epsilon)

        # Decay epsilon
        epsilon = max(
            MIN_EPSILON,
            epsilon * EPSILON_DECAY
        )

    return (
        q_table,
        episode_rewards,
        episode_steps,
        episode_success,
        epsilon_values
    )


