GRID_SIZE = 5

LEARNING_RATE = 0.10
DISCOUNT_FACTOR = 0.95

INITIAL_EPSILON = 1.00
MIN_EPSILON = 0.01
EPSILON_DECAY = 0.995

TRAINING_EPISODES = 1000
MAX_STEPS = 200

# Rewards
GOAL_REWARD = 100
MOVE_REWARD = -1
OBSTACLE_REWARD = -10
INVALID_REWARD = -10

# Actions
UP = 0
DOWN = 1
